#!/usr/bin/env python3
"""Generate src/nycZips.js — the centre of every NYC ZIP code, so a ZIP typed
into the header search ("10027") can rank pools by distance instead of only
matching pools that happen to sit inside it.

Source: NYC Open Data "Modified Zip Code Tabulation Areas (MODZCTA)"
(pri4-ifjk). Each area lists the postal ZIPs folded into it (10027 also covers
10115, a single-building ZIP), and every one of them maps to the area's centre.

    python3 scripts/make_zips.py                   # download, then generate
    python3 scripts/make_zips.py modzcta.geojson   # use a file you already have

Standard library only. ZIP areas barely move; rerun only if the source changes.
"""

import json
import sys
import tempfile
import urllib.request
from pathlib import Path

SOURCE = "https://data.cityofnewyork.us/resource/pri4-ifjk.geojson?$limit=1000"
OUT = Path(__file__).resolve().parent.parent / "src" / "nycZips.js"


def ring_centroid(ring):
    """Area and area-weighted centroid of one ring, planar in lng/lat — fine at
    the scale of a ZIP code."""
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        cross = x1 * y2 - x2 * y1
        a += cross
        cx += (x1 + x2) * cross
        cy += (y1 + y2) * cross
    if a == 0:
        return 0.0, ring[0][0], ring[0][1]
    return a / 2, cx / (3 * a), cy / (3 * a)


def centre(geometry):
    """The weighted centre of a (multi)polygon's outer rings."""
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    total = sx = sy = 0.0
    for poly in polys:
        area, x, y = ring_centroid(poly[0])
        area = abs(area)
        total += area
        sx += x * area
        sy += y * area
    return sy / total, sx / total  # lat, lng


def main():
    if len(sys.argv) > 1:
        src = Path(sys.argv[1])
    else:
        src = Path(tempfile.mkdtemp()) / "modzcta.geojson"
        urllib.request.urlretrieve(SOURCE, src)
    data = json.loads(src.read_text())

    zips = {}
    for f in data["features"]:
        p = f["properties"]
        if not f.get("geometry") or p.get("modzcta") in (None, "99999"):
            continue
        lat, lng = centre(f["geometry"])
        codes = {p["modzcta"]}
        for field in ("zcta", "label"):
            codes |= {c.strip() for c in (p.get(field) or "").split(",") if c.strip()}
        for code in codes:
            if code.isdigit() and len(code) == 5:
                zips[code] = [round(lat, 4), round(lng, 4)]

    body = json.dumps(dict(sorted(zips.items())), separators=(",", ":"))
    OUT.write_text(
        "// Generated by scripts/make_zips.py from NYC Open Data MODZCTA (pri4-ifjk).\n"
        "// ZIP -> [lat, lng] of its area's centre. Do not edit by hand.\n"
        f"export const NYC_ZIPS = {body}\n"
    )
    print(f"wrote {OUT} ({len(zips)} ZIPs, {OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
